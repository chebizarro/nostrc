#!/usr/bin/env python3
"""Run with python3 -I. Independent binary64 pins; stdout is mmp_pins.h.

Matches core/src/proto/mmp at 6aa80504baa0fa312b392009eea0e3e59fb6fe4c:
no fused multiply-add, no decimal tolerance, no libm. Integer RTT/jitter are
referenced here too so the sequences pin truncation/shift order explicitly.
"""
import struct


def bits(x):
    return struct.unpack('>Q', struct.pack('>d', x))[0]


def ewma(short, long, x):
    return short + 0.25 * (x - short), long + (1.0 / 32.0) * (x - long)


def etx(forward, reverse):
    product = forward * reverse
    return 100.0 if product <= 0.0 else min(100.0, max(1.0, 1.0 / product))


def array(name, rows, columns):
    print(f'static const uint64_t {name}[][{columns}] = {{')
    for row in rows:
        print('    {' + ', '.join(f'UINT64_C(0x{bits(x):016x})' for x in row) + '},')
    print('};')


def emit():
    print('/* Generated by python3 -I tests/tools/mmp_reference.py; do not edit. */')
    print('#ifndef FIPS_MMP_PINS_H\n#define FIPS_MMP_PINS_H')
    short = long = 0.0
    rows = []
    for x in [0.0, 100.0, 50.0, 1.0, 1e20, 1e-10, -3.5, 0.0]:
        short, long = ewma(short, long, x)
        rows.append((short, long))
    array('mmp_ewma_pins', rows, 2)
    rows = []
    short = long = None
    # Accepted reports: forward ratio uses interval packets/span; reverse is the
    # ratio available BEFORE this report (the refresh after it does not step).
    for forward, reverse in [(.8, .9), (.5, 1.0), (1.0, .5), (0.0, .75), (.99, .99), (.8, .9)]:
        raw = etx(forward, reverse)
        if short is None:
            short = long = raw
        else:
            short, long = ewma(short, long, raw)
        rows.append((raw, short, long))
    array('mmp_etx_pins', rows, 3)
    print(f'#define MMP_LOSSY_ETX_BITS UINT64_C(0x{bits(etx(.9, .95)):016x})')
    print('static const int64_t mmp_srtt_pins[][2] = {')
    srtt = var = None
    for rtt in [10000, 45001, 0, 500000, 999, 4294967295000]:
        if srtt is None:
            srtt, var = rtt, rtt // 2
        else:
            err = abs(srtt - rtt)
            var = var - (var >> 2) + (err >> 2)
            srtt = srtt - (srtt >> 3) + (rtt >> 3)
        print(f'    {{INT64_C({srtt}), INT64_C({var})}},')
    print('};')
    # OWD sample stream from state.rs: slope in us/s against receive ms.
    xs = [0, 120, 210, 330, 400]
    ys = [0, 20000, 10000, 30000, 0]
    mx = sum(float(x) for x in xs) / len(xs)
    my = sum(float(y) for y in ys) / len(ys)
    num = den = 0.0
    for x, y in zip(xs, ys):
        dx, dy = float(x) - mx, float(y) - my
        num += dx * dy
        den += dx * dx
    print(f'#define MMP_OWD_STREAM_TREND {int((num / den) * 1000.0)}')
    print('#endif')


if __name__ == '__main__':
    import contextlib
    import io
    import pathlib
    import sys
    output = io.StringIO()
    with contextlib.redirect_stdout(output):
        emit()
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        expected = pathlib.Path(sys.argv[2]).read_text()
        if expected != output.getvalue():
            raise SystemExit('MMP arithmetic pins differ from independent reference')
        print('MMP independent arithmetic pins match')
    elif len(sys.argv) == 1:
        print(output.getvalue(), end='')
    else:
        raise SystemExit('usage: python3 -I mmp_reference.py [--check mmp_pins.h]')
