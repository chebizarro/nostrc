#!/usr/bin/env bash
# Run the teardown-sensitive GUI suites with replayable seeded completion
# scheduling. All fixtures use local relays and private clipboards.
#
# GH_TEST_EVIDENCE_DIR (optional): keep failure evidence there. Core dumps are
# enabled for the tests (the caller points kernel.core_pattern into this
# directory, ideally as core.%p.%E); after a failed seed each core becomes a
# gdb backtrace of every thread (a fatal critical raises SIGTRAP), and the
# seed's completion trace and CTest log are kept. Nothing is collected or
# slowed down when every seed passes.
set -euo pipefail
build="${1:-build}"
repeats="${2:-2}"
case "$repeats" in ''|*[!0-9]*) echo 'repeats must be a positive integer' >&2; exit 2 ;; esac
[ "$repeats" -gt 0 ] || { echo 'repeats must be positive' >&2; exit 2; }
export GH_TEST_ASYNC_JITTER_MS="${GH_TEST_ASYNC_JITTER_MS:-50}"
seed_list="${GH_TEST_ASYNC_SEEDS:-${GH_TEST_ASYNC_SEED:-20261004 17 29}}"
read -r -a seeds <<< "$seed_list"
[ "${#seeds[@]}" -gt 0 ] || { echo 'at least one seed is required' >&2; exit 2; }
regex='^(groundhog-mls-ui-gui|groundhog-conversation-menu-gui|groundhog-composer|groundhog-attachment-ui)$'
trace_dir="$(mktemp -d)"
trap 'rm -rf "$trace_dir"' EXIT
evidence="${GH_TEST_EVIDENCE_DIR:-}"
if [ -n "$evidence" ]; then
  mkdir -p "$evidence"
  ulimit -c unlimited || echo "warning: core dumps unavailable (ulimit -c $(ulimit -c))" >&2
  [ -r /proc/sys/kernel/core_pattern ] && echo "core_pattern: $(cat /proc/sys/kernel/core_pattern)"
fi

# Symbolizes every core under the evidence directory, once each.
backtraces() {
  local core exe out
  command -v gdb >/dev/null || { echo 'gdb not installed; cores kept unsymbolized' >&2; return 0; }
  for core in "$evidence"/core*; do
    [ -f "$core" ] && [ ! -e "$core.bt" ] || continue
    # core.<pid>.<%E: the executable's path, '/' written as '!'>; otherwise
    # the command line the core records (cut at 80 bytes by the kernel).
    exe="${core##*/}"; exe="${exe#core.*.}"; exe="${exe//!//}"
    [ -x "$exe" ] || exe="$(gdb -nx -batch -c "$core" 2>/dev/null |
      sed -n "s/^Core was generated by \`\([^ ']*\).*/\1/p" | head -n1)"
    out="$core.bt"
    {
      echo "### core=$core executable=${exe:-unknown}"
      # Groundhog frames are symbolized from the Debug build; system
      # libraries through Ubuntu's debuginfod when it answers in time.
      DEBUGINFOD_URLS="${DEBUGINFOD_URLS:-https://debuginfod.ubuntu.com}" \
        timeout 900 gdb -nx -batch -iex 'set debuginfod enabled on' \
          -ex 'set print frame-arguments all' -ex 'bt full' -ex 'thread apply all bt full' \
          ${exe:+"$exe"} -c "$core" 2>&1 || echo "gdb exited $?"
    } > "$out"
    sed -n '1,/^Thread [0-9]* (/p' "$out"
    echo "Full backtraces: $out"
  done
}
for seed in "${seeds[@]}"; do
  case "$seed" in ''|*[!0-9]*) echo "invalid seed: $seed" >&2; exit 2 ;; esac
  export GH_TEST_ASYNC_SEED="$seed"
  export GH_TEST_ASYNC_TRACE="$trace_dir/seed-$seed.trace"
  : > "$GH_TEST_ASYNC_TRACE"
  echo "==> GUI lifetime jitter seed=$seed maximum=${GH_TEST_ASYNC_JITTER_MS}ms trace=$GH_TEST_ASYNC_TRACE"
  cmd=(ctest --test-dir "$build" --no-tests=error --output-on-failure --parallel 4
       --repeat "until-fail:$repeats" -R "$regex")
  status=0
  if [ "$(uname -s)" = Linux ] && [ -z "${DISPLAY:-}" ]; then
    dbus-run-session -- xvfb-run -a -s '-screen 0 1280x800x24' "${cmd[@]}" || status=$?
  else
    "${cmd[@]}" || status=$?
  fi
  if [ "$status" -ne 0 ]; then
    if [ -n "$evidence" ]; then
      cp "$GH_TEST_ASYNC_TRACE" "$evidence/"
      cp "$build/Testing/Temporary/LastTest.log" "$evidence/LastTest-seed-$seed.log" 2>/dev/null || true
      backtraces
    fi
    echo "seed=$seed failed (ctest exit $status)" >&2
    exit "$status"
  fi
  sed -n 's/^queued .* pid=\([^ ]*\) id=\([^ ]*\)$/\1:\2/p' "$GH_TEST_ASYNC_TRACE" | sort > "$trace_dir/queued"
  sed -n 's/^delivered .* pid=\([^ ]*\) id=\([^ ]*\)$/\1:\2/p' "$GH_TEST_ASYNC_TRACE" | sort > "$trace_dir/delivered"
  if ! diff -u "$trace_dir/queued" "$trace_dir/delivered"; then
    echo "seed=$seed left injected completions undelivered" >&2
    exit 1
  fi
  for site in conversation-menu clipboard mls-invitee media-attachment group-info-service new-group-service; do
    if ! grep -q "^delivered $site " "$GH_TEST_ASYNC_TRACE"; then
      echo "seed=$seed did not deliver an injected $site completion" >&2
      echo "Recorded sites:" >&2
      sed -n 's/^delivered \([^ ]*\).*/\1/p' "$GH_TEST_ASYNC_TRACE" | sort -u >&2
      exit 1
    fi
  done
  echo "==> Seed $seed: all six injected completion families delivered"
done
