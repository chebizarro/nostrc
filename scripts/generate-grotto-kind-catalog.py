#!/usr/bin/env python3
"""Derive Grotto's searchable display catalogue from the in-tree kind registry.

Values stay symbolic C constants. This is display data, never consent policy;
Full/Medium/default confirmation sets remain in signer_permission_policy.h.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'libnostr/include/nostr-kinds.h'
target = root / 'apps/grotto/src/ui/kind-catalog.inc'
rows, panel_rows, seen = [], [], set()
for line in source.read_text().splitlines():
    parts = line.split()
    if len(parts) < 3 or parts[0] != '#define' or not parts[1].startswith('NOSTR_KIND_') or not parts[2].isdecimal():
        continue
    value = int(parts[2])
    if value > 65535 or value in seen:
        continue
    seen.add(value)
    caption = parts[1].removeprefix('NOSTR_KIND_').replace('_', ' ').capitalize()
    rows.append((value, f'  {{{parts[1]}, N_("{caption}")}},'))
    panel_rows.append((value, f'  {{{value}, N_("{caption}")}},'))
content = '/* Generated by scripts/generate-grotto-kind-catalog.py; do not edit. */\n' + '\n'.join(row for _, row in sorted(rows)) + '\n'
panel_content = '/* Generated display data; no policy. Run scripts/generate-grotto-kind-catalog.py. */\n' + '\n'.join(row for _, row in sorted(panel_rows)) + '\n'
for destination, generated in [(target, content), (root / 'gnome/grotto-panels/src/kind-catalog.inc', panel_content)]:
    if '--check' in sys.argv:
        if not destination.exists() or destination.read_text() != generated:
            sys.exit('Grotto kind catalogue drift: run scripts/generate-grotto-kind-catalog.py')
    else:
        destination.write_text(generated)
